"""Download the official source PDFs listed in data/sources.json into data/raw/
and write data/SOURCES.md with checksums.

Sources marked "manual" are tried automatically, but if the site is unreachable
(India Code often is) the script prints where to save a browser download instead
of failing.

Usage (from backend/):
    python -m scripts.download_sources          # download missing files
    python -m scripts.download_sources --force  # re-download everything
"""

import argparse
import hashlib
import json
import re
import sys
import time
from pathlib import Path

import truststore

# egazette.gov.in does not send its full certificate chain; the Windows/macOS
# system store can complete it, certifi cannot.
truststore.inject_into_ssl()

import pymupdf  # noqa: E402
import requests  # noqa: E402

BACKEND = Path(__file__).resolve().parents[1]
DATA = BACKEND / "data"
RAW = DATA / "raw"
MANIFEST = DATA / "sources.json"
SOURCES_MD = DATA / "SOURCES.md"
HEADERS = {"User-Agent": "Mozilla/5.0 (LabourLens research project)"}


def fetch(url: str, retries: int = 3) -> bytes:
    for attempt in range(1, retries + 1):
        try:
            r = requests.get(url, headers=HEADERS, timeout=180)
            r.raise_for_status()
            if not r.content.startswith(b"%PDF"):
                raise ValueError("response is not a PDF")
            return r.content
        except Exception as e:
            if attempt == retries:
                raise
            print(f"   retry {attempt} after error: {e}")
            time.sleep(5 * attempt)
    raise RuntimeError("unreachable")


def contains_title(pdf: Path, expected: str) -> bool:
    """Check the expected title appears in the text (whitespace-insensitive)."""
    norm = lambda s: re.sub(r"\s+", " ", s).lower()
    with pymupdf.open(pdf) as doc:
        text = norm(" ".join(page.get_text() for page in doc))
    return norm(expected) in text


def write_sources_md(manifest: dict, rows: list[dict], missing: list[dict]) -> None:
    lines = [
        "# Sources",
        "",
        f"**Corpus as of:** {manifest['corpus_as_of']}  ",
        f"**Scope:** {manifest['scope']}",
        "",
        "Generated by `python -m scripts.download_sources`. Do not edit by hand; edit `sources.json`.",
        "",
        "| ID | Document | Citation | Publisher | Pages | SHA-256 (first 12) |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| `{r['id']}` | [{r['title']}]({r['url']}) | {r['citation']} | {r['publisher']} "
            f"| {r['pages']} | `{r['sha256'][:12]}` |"
        )
    notes = [r for r in rows if r.get("notes")]
    if notes:
        lines += ["", "## Parsing notes", ""]
        lines += [f"- `{r['id']}`: {r['notes']}" for r in notes]
    if missing:
        lines += ["", "## Still to collect (manual download)", ""]
        lines += [
            f"- [ ] **{m['title']}**: download from {m['url']} and save as `data/raw/{m['id']}.pdf`"
            for m in missing
        ]
    SOURCES_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--force", action="store_true", help="re-download existing files")
    args = parser.parse_args()

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    RAW.mkdir(parents=True, exist_ok=True)

    rows, failures, missing = [], [], []
    for src in manifest["sources"]:
        path = RAW / f"{src['id']}.pdf"
        print(f"- {src['id']}")
        if args.force or not path.exists():
            try:
                path.write_bytes(fetch(src["url"], retries=1 if src.get("manual") else 3))
            except Exception as e:
                if src.get("manual") and not path.exists():
                    print(f"   MANUAL: could not fetch ({e.__class__.__name__}).")
                    print(f"   Download from {src['url']} and save as {path.relative_to(BACKEND)}")
                    missing.append(src)
                    continue
                print(f"   FAILED: {e}")
                failures.append(src["id"])
                continue
        if not contains_title(path, src["expect"]):
            print(f"   FAILED: expected title '{src['expect']}' not found in PDF text")
            failures.append(src["id"])
            continue
        with pymupdf.open(path) as doc:
            pages = len(doc)
        sha = hashlib.sha256(path.read_bytes()).hexdigest()
        print(f"   ok: {pages} pages, {path.stat().st_size // 1024} KB")
        rows.append({**src, "pages": pages, "sha256": sha})

    write_sources_md(manifest, rows, missing)
    print(
        f"\n{len(rows)} ok, {len(missing)} need manual download, {len(failures)} failed. "
        f"Wrote {SOURCES_MD.relative_to(BACKEND)}"
    )
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
